export const convertCurrency = (amount: number, from: Currency, to: Currency): number => {
  if (from === to) return amount

  const rate = exchangeRates[from]?.[to]
  if (rate) {
    return amount * rate
  }

  // Fallback: convert through USD if direct rate not available
  if (from !== "USD" && to !== "USD") {
    const toUSD = exchangeRates[from]?.["USD"] || 1
    const fromUSD = exchangeRates["USD"]?.[to] || 1
    return amount * toUSD * fromUSD
  }

  return amount
}

export const fetchRealTimeExchangeRate = async (
  amount: number,
  fromCurrency: Currency,
  toCurrency: Currency,
): Promise<ConversionResult> => {
  // If currencies are the same, return immediately
  if (fromCurrency === toCurrency) {
    return {
      amount,
      rate: 1,
      timestamp: new Date().toISOString(),
      success: true,
    }
  }

  try {
    const response = await fetch(`https://api.exchangerate-api.com/v4/latest/${fromCurrency}`)

    if (!response.ok) {
      throw new Error(`API error: ${response.status}`)
    }

    const data = await response.json()

    if (!data.rates || !data.rates[toCurrency]) {
      throw new Error(`Rate not available for ${toCurrency}`)
    }

    const rate = data.rates[toCurrency]
    const convertedAmount = amount * rate

    return {
      amount: convertedAmount,
      rate: rate,
      timestamp: data.time_last_updated ? new Date(data.time_last_updated * 1000).toISOString() : data.date,
      success: true,
    }
  } catch (error) {
    console.error("Real-time conversion failed:", error)

    // Fallback to static rates
    const fallbackAmount = convertCurrency(amount, fromCurrency, toCurrency)
    return {
      amount: fallbackAmount,
      rate: fallbackAmount / amount,
      timestamp: new Date().toISOString(),
      success: false,
      error: error instanceof Error ? error.message : "Unknown error",
    }
  }
}

// Add this hook for components to easily use real-time conversion
export const useRealTimeConversion = (amount: number, fromCurrency: Currency, toCurrency: Currency) => {
  const [result, setResult] = useState<ConversionResult | null>(null)
  const [loading, setLoading] = useState<boolean>(true)

  useEffect(() => {
    let isMounted = true

    // Initial conversion using static rates
    const staticAmount = convertCurrency(amount, fromCurrency, toCurrency)
    if (isMounted) {
      setResult({
        amount: staticAmount,
        rate: staticAmount / amount,
        timestamp: new Date().toISOString(),
        success: true,
      })
    }

    // Fetch real-time rates
    const fetchRates = async () => {
      try {
        const realTimeResult = await fetchRealTimeExchangeRate(amount, fromCurrency, toCurrency)
        if (isMounted) {
          setResult(realTimeResult)
          setLoading(false)
        }
      } catch (error) {
        if (isMounted) {
          setLoading(false)
        }
      }
    }

    fetchRates()

    return () => {
      isMounted = false
    }
  }, [amount, fromCurrency, toCurrency])

  return { result, loading }
}

export const formatCurrency = (amount: number, currency: Currency): string => {
  const currencyInfo = currencies[currency]
  return `${currencyInfo.symbol}${amount.toFixed(2)}`
}
